#!/usr/bin/env bun
/**
 * Manage access to Anthropic-hosted claude.ai MCP connectors from any client.
 *
 * Subcommands:
 *   sync      Refresh connectors.json from your claude.ai org (do this if a
 *             connector was re-added, or a tool went missing).
 *   list      Show connectors in the local registry.
 *   status    Health-check: token validity + live handshake per connector.
 *   token     Print a valid account token (auto-refreshing).
 *   tools     List the tools a connector exposes.
 *   call      Invoke a tool directly, for debugging.
 *   doctor    Diagnose common breakages.
 *
 * See ../README.md for how this works and how to extend it.
 */

import {
  ConnectorError,
  PROXY_BASE,
  REGISTRY,
  accessToken,
  expandFileArgs,
  fetchConnectors,
  httpPost,
  keychainRead,
  loadRegistry,
  resolve,
  slugify,
} from "../lib/common.ts";

// Friendly aliases for the connectors worth short names. Anything not listed
// gets a slugified name from the claude.ai connector title.
const PREFERRED_ALIASES: Record<string, string> = {
  "Slack": "slack",
  "Google Drive": "drive",
  "Gmail": "gmail",
  "Google Calendar": "calendar",
  "Glean": "glean",
  "Zoom for Claude": "zoom",
  "Amplitude": "amplitude",
  "Asana": "asana",
  "Linear": "linear",
  "Notion": "notion",
};

function pad(s: string, width: number): string {
  return s.length >= width ? s : s + " ".repeat(width - s.length);
}

// ---------------------------------------------------------------------------
// RPC helper: minimal initialize -> call sequence against one connector.
// ---------------------------------------------------------------------------

async function rpc(
  alias: string,
  method: string,
  params: Record<string, unknown>,
): Promise<Record<string, any>> {
  const serverId = await resolve(alias);
  const url = `${PROXY_BASE}/${serverId}`;
  const headers = {
    Authorization: `Bearer ${await accessToken()}`,
    "Content-Type": "application/json",
    Accept: "application/json, text/event-stream",
    // Undocumented but mandatory; the gateway 400s without it.
    "X-Mcp-Client-Session-Id": crypto.randomUUID(),
  };

  async function post(payload: unknown): Promise<Record<string, any>> {
    const raw = await httpPost(url, payload, headers);
    for (let line of raw.split(/\r?\n/)) {
      line = line.trim();
      if (line.startsWith("data:")) {
        line = line.slice(5).trim();
      }
      if (line.startsWith("{")) {
        return JSON.parse(line);
      }
    }
    return {};
  }

  await post({
    jsonrpc: "2.0",
    id: 1,
    method: "initialize",
    params: {
      protocolVersion: "2025-06-18",
      capabilities: {},
      clientInfo: { name: "claude-connectors", version: "1" },
    },
  });
  await post({ jsonrpc: "2.0", method: "notifications/initialized" });
  return post({ jsonrpc: "2.0", id: 2, method, params });
}

// ---------------------------------------------------------------------------
// Subcommands
// ---------------------------------------------------------------------------

async function cmdSync(opts: Options): Promise<number> {
  const connectors = await fetchConnectors();
  const connected = connectors.filter((c) => c.connected);

  const servers: Record<string, { id: string; name: string }> = {};
  for (const c of connected) {
    const alias = PREFERRED_ALIASES[c.name] ?? slugify(c.name);
    servers[alias] = { id: c.installedServerId, name: c.name };
  }

  const sortedServers: Record<string, { id: string; name: string }> = {};
  for (const alias of Object.keys(servers).sort()) {
    sortedServers[alias] = servers[alias];
  }

  const payload = {
    _comment:
      "Generated by `claude-connectors sync`. Maps friendly aliases to " +
      "claude.ai installedServerId values. Safe to re-generate at any time.",
    servers: sortedServers,
  };
  await Bun.write(REGISTRY, JSON.stringify(payload, null, 2) + "\n");

  console.log(`Wrote ${REGISTRY}`);
  console.log(
    `${Object.keys(servers).length} connected connector(s) of ${connectors.length} available:\n`,
  );
  for (const alias of Object.keys(sortedServers)) {
    console.log(`  ${pad(alias, 12)} ${sortedServers[alias].name}`);
  }

  const unconnected = connectors.filter((c) => !c.connected).map((c) => c.name);
  if (unconnected.length && opts.verbose) {
    console.log(`\nNot authenticated (${unconnected.length}):`);
    for (const name of [...unconnected].sort()) {
      console.log(`  - ${name}`);
    }
    console.log('\nAuthenticate with: claude mcp login "claude.ai <Name>"');
  }
  return 0;
}

async function cmdList(_opts: Options): Promise<number> {
  const registry = await loadRegistry();
  for (const alias of Object.keys(registry.servers).sort()) {
    const meta = registry.servers[alias];
    console.log(`${pad(alias, 12)} ${pad(meta.name, 22)} ${meta.id}`);
  }
  return 0;
}

async function cmdTools(opts: Options): Promise<number> {
  const resp = await rpc(opts.connector!, "tools/list", {});
  if ("error" in resp) {
    process.stderr.write(`error: ${JSON.stringify(resp.error)}\n`);
    return 1;
  }
  const tools = resp.result?.tools ?? [];
  for (const tool of tools) {
    if (opts.verbose) {
      const desc = (tool.description ?? "").split("\n")[0].slice(0, 90);
      console.log(`${pad(tool.name, 40)} ${desc}`);
    } else {
      console.log(tool.name);
    }
  }
  process.stderr.write(`\n${tools.length} tool(s)\n`);
  return 0;
}

async function cmdCall(opts: Options): Promise<number> {
  let args: any;
  try {
    args = JSON.parse(opts.argsJson ?? "{}");
  } catch (exc) {
    process.stderr.write(`--args must be valid JSON: ${exc}\n`);
    return 2;
  }
  // Expand virtual file-path arguments (textContentFile/base64ContentFile).
  if (args !== null && typeof args === "object" && !Array.isArray(args)) {
    try {
      args = await expandFileArgs(args);
    } catch (exc) {
      process.stderr.write(`error: ${exc instanceof Error ? exc.message : exc}\n`);
      return 1;
    }
  }
  const resp = await rpc(opts.connector!, "tools/call", {
    name: opts.tool,
    arguments: args,
  });
  console.log(JSON.stringify(resp, null, 2));
  return "error" in resp ? 1 : 0;
}

async function cmdToken(_opts: Options): Promise<number> {
  console.log(await accessToken());
  return 0;
}

async function cmdStatus(_opts: Options): Promise<number> {
  const blob = await keychainRead();
  const oauth = blob.claudeAiOauth ?? {};
  const expiresAt: number = oauth.expiresAt ?? 0;
  const mins = (expiresAt - Date.now()) / 60000;
  console.log(`account token : expires in ${Math.round(mins)} min`);
  console.log(`scopes        : ${(oauth.scopes ?? []).join(", ")}`);
  console.log();

  let registry;
  try {
    registry = await loadRegistry();
  } catch (exc) {
    process.stderr.write(`${exc instanceof Error ? exc.message : exc}\n`);
    return 1;
  }

  let failures = 0;
  for (const alias of Object.keys(registry.servers).sort()) {
    try {
      const resp = await rpc(alias, "tools/list", {});
      if ("error" in resp) {
        console.log(`  ${pad(alias, 12)} FAIL  ${(resp.error?.message ?? "").slice(0, 60)}`);
        failures += 1;
      } else {
        const count = (resp.result?.tools ?? []).length;
        console.log(`  ${pad(alias, 12)} ok    ${count} tools`);
      }
    } catch (exc) {
      if (exc instanceof ConnectorError) {
        console.log(`  ${pad(alias, 12)} FAIL  ${exc.message}`);
        failures += 1;
      } else {
        throw exc;
      }
    }
  }
  return failures ? 1 : 0;
}

async function cmdDoctor(_opts: Options): Promise<number> {
  console.log("Checking environment...\n");
  let ok = true;

  if (Bun.which("curl")) {
    console.log(
      "  [ok]   curl present (needed: bundled CA stores reject the corp TLS proxy)",
    );
  } else {
    console.log("  [FAIL] curl not found");
    ok = false;
  }

  try {
    await keychainRead();
    console.log("  [ok]   keychain item readable");
  } catch (exc) {
    console.log(`  [FAIL] ${exc instanceof Error ? exc.message : exc}`);
    ok = false;
  }

  try {
    await accessToken();
    console.log("  [ok]   account token valid (refreshed if needed)");
  } catch (exc) {
    console.log(`  [FAIL] ${exc instanceof Error ? exc.message : exc}`);
    ok = false;
  }

  if (await Bun.file(REGISTRY).exists()) {
    const n = Object.keys((await loadRegistry()).servers).length;
    console.log(`  [ok]   registry present (${n} connectors)`);
  } else {
    console.log("  [WARN] no registry; run: claude-connectors sync");
  }

  const probe = Bun.spawn(
    [
      "curl", "-sS", "-o", "/dev/null", "-w", "%{http_code}",
      "--max-time", "10", PROXY_BASE + "/probe",
    ],
    { stdout: "pipe", stderr: "pipe" },
  );
  const [probeOut] = await Promise.all([
    new Response(probe.stdout).text(),
    probe.exited,
  ]);
  if (probeOut.trim()) {
    console.log(`  [ok]   gateway reachable (HTTP ${probeOut.trim()})`);
  } else {
    console.log("  [FAIL] gateway unreachable");
    ok = false;
  }

  console.log(ok ? "\nAll good." : "\nSee README.md -> Troubleshooting.");
  return ok ? 0 : 1;
}

// ---------------------------------------------------------------------------
// Arg parsing
// ---------------------------------------------------------------------------

interface Options {
  verbose: boolean;
  connector?: string;
  tool?: string;
  argsJson?: string;
}

const COMMANDS: Record<
  string,
  { run: (opts: Options) => Promise<number>; positional: string[] }
> = {
  sync: { run: cmdSync, positional: [] },
  list: { run: cmdList, positional: [] },
  status: { run: cmdStatus, positional: [] },
  token: { run: cmdToken, positional: [] },
  doctor: { run: cmdDoctor, positional: [] },
  tools: { run: cmdTools, positional: ["connector"] },
  call: { run: cmdCall, positional: ["connector", "tool"] },
};

function usage(): number {
  process.stderr.write(
    "usage: connectors.ts <sync|list|status|token|tools|call|doctor> [args]\n",
  );
  return 2;
}

async function main(): Promise<number> {
  const argv = Bun.argv.slice(2);
  if (argv.length === 0) {
    return usage();
  }
  const cmd = argv[0];
  const spec = COMMANDS[cmd];
  if (!spec) {
    process.stderr.write(`unknown command: ${cmd}\n`);
    return usage();
  }

  const opts: Options = { verbose: false, argsJson: "{}" };
  const positionals: string[] = [];
  for (let i = 1; i < argv.length; i++) {
    const a = argv[i];
    if (a === "-v" || a === "--verbose") {
      opts.verbose = true;
    } else if (a === "--args") {
      opts.argsJson = argv[++i];
    } else if (a.startsWith("--args=")) {
      opts.argsJson = a.slice("--args=".length);
    } else {
      positionals.push(a);
    }
  }

  spec.positional.forEach((name, idx) => {
    (opts as any)[name] = positionals[idx];
  });

  for (const name of spec.positional) {
    if (!(opts as any)[name]) {
      process.stderr.write(`${cmd}: missing required argument: ${name}\n`);
      return 2;
    }
  }

  try {
    return await spec.run(opts);
  } catch (exc) {
    if (exc instanceof ConnectorError) {
      process.stderr.write(`error: ${exc.message}\n`);
      return 1;
    }
    throw exc;
  }
}

process.exit(await main());
